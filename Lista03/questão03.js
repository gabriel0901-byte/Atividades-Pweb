const a = 15;
const b = 5;
const operacao = "*";
switch(operacao) {
    case "*":
        console.log(a * b);
        break;
    case "/":
        console.log(a / b);
        break;
    case "+":
            console.log(a + b);
            break;
    case "-":
                console.log(a - b);
                break;    
    default:
        console.log("Operação inválida");
}
    